//  ClipboardHistoryManager.swift
//  boringNotch
//
//  Watches the system clipboard and keeps a history of copied items.
//

import AppKit
import Combine
import CryptoKit
import Defaults
import Foundation

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable {
        case text
        case link
        case image
        case file
    }

    let id: UUID
    var kind: Kind
    /// Text, link, or newline-separated file paths. Empty for images.
    var text: String
    /// File name of the stored image (images only).
    var imageFileName: String?
    /// Hash of the image data, used to spot duplicates.
    var imageHash: String?
    var date: Date
    var isPinned: Bool
    var sourceBundleID: String?

    var fileURLs: [URL] {
        guard kind == .file else { return [] }
        return text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
    }

    func isSameContent(as other: ClipboardItem) -> Bool {
        guard kind == other.kind else { return false }
        if kind == .image { return imageHash != nil && imageHash == other.imageHash }
        return text == other.text
    }
}

@MainActor
final class ClipboardHistoryManager: ObservableObject {
    static let shared = ClipboardHistoryManager()

    @Published private(set) var items: [ClipboardItem] = []
    /// Id of the item that was just copied back, for the "Copied" checkmark.
    @Published private(set) var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var cancellables = Set<AnyCancellable>()
    private var copiedResetTask: Task<Void, Never>?

    /// Images bigger than this are not kept, so the history stays small.
    private let maxImageBytes = 10 * 1024 * 1024

    /// Types that password managers and similar apps set to say "don't record this".
    private let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    private let storageFolder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("ClipboardHistory", isDirectory: true)
    }()

    private var indexFile: URL { storageFolder.appendingPathComponent("history.json") }
    private let saveQueue = DispatchQueue(label: "boringNotch.clipboardHistory.save", qos: .utility)

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        try? FileManager.default.createDirectory(at: storageFolder, withIntermediateDirectories: true)
        load()

        Defaults.publisher(.enableClipboardHistory)
            .map(\.newValue)
            .removeDuplicates()
            .receive(on: RunLoop.main)
            .sink { [weak self] enabled in
                if enabled {
                    self?.startWatching()
                } else {
                    self?.stopWatching()
                    if BoringViewCoordinator.shared.currentView == .clipboard {
                        BoringViewCoordinator.shared.currentView = .home
                    }
                }
            }
            .store(in: &cancellables)

        Defaults.publisher(.clipboardHistoryLimit)
            .dropFirst()
            .receive(on: RunLoop.main)
            .sink { [weak self] _ in
                self?.trim()
                self?.save()
            }
            .store(in: &cancellables)
    }

    // MARK: - Watching

    func startWatching() {
        guard timer == nil else { return }
        // Don't record whatever was copied while watching was off.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.checkPasteboard() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stopWatching() {
        timer?.invalidate()
        timer = nil
    }

    private func checkPasteboard() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: privateTypes) else { return }

        if let item = readItem() {
            add(item)
        }
    }

    private func readItem() -> ClipboardItem? {
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // Files copied in Finder
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipboardItem(id: UUID(), kind: .file, text: urls.map(\.path).joined(separator: "\n"),
                                 date: Date(), isPinned: false, sourceBundleID: source)
        }

        // Text and links
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace)
                && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
                && URL(string: trimmed) != nil
            return ClipboardItem(id: UUID(), kind: isLink ? .link : .text, text: string,
                                 date: Date(), isPinned: false, sourceBundleID: source)
        }

        // Images
        if let data = imageData(), data.count <= maxImageBytes {
            let id = UUID()
            let fileName = "\(id.uuidString).png"
            do {
                try data.write(to: storageFolder.appendingPathComponent(fileName))
            } catch {
                return nil
            }
            return ClipboardItem(id: id, kind: .image, text: "", imageFileName: fileName,
                                 imageHash: SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined(), date: Date(), isPinned: false,
                                 sourceBundleID: source)
        }

        return nil
    }

    private func imageData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: - Editing the history

    private func add(_ item: ClipboardItem) {
        if let index = items.firstIndex(where: { $0.isSameContent(as: item) }) {
            // Already in the history: move it to the top instead of adding a duplicate.
            var existing = items.remove(at: index)
            existing.date = item.date
            existing.sourceBundleID = item.sourceBundleID ?? existing.sourceBundleID
            items.insert(existing, at: 0)
            if let fileName = item.imageFileName, fileName != existing.imageFileName {
                removeImageFile(fileName)
            }
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    /// Puts an item back on the clipboard so it can be pasted.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text, forType: .string)
        case .file:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .image:
            guard let image = image(for: item) else { return }
            pasteboard.writeObjects([image])
        }
        // Don't record our own copy as a new item.
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }

        lastCopiedID = item.id
        copiedResetTask?.cancel()
        copiedResetTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: .seconds(1.5))
            guard !Task.isCancelled else { return }
            self?.lastCopiedID = nil
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        if let fileName = item.imageFileName { removeImageFile(fileName) }
        save()
    }

    /// Removes everything except pinned items.
    func clearUnpinned() {
        let removed = items.filter { !$0.isPinned }
        items.removeAll { !$0.isPinned }
        removed.compactMap(\.imageFileName).forEach(removeImageFile)
        save()
    }

    /// Keeps pinned items plus the newest unpinned ones, up to the limit.
    private func trim() {
        let limit = max(1, Defaults[.clipboardHistoryLimit])
        var unpinnedSeen = 0
        var kept: [ClipboardItem] = []
        for item in items {
            if item.isPinned {
                kept.append(item)
            } else if unpinnedSeen < limit {
                unpinnedSeen += 1
                kept.append(item)
            } else if let fileName = item.imageFileName {
                removeImageFile(fileName)
            }
        }
        items = kept
    }

    // MARK: - Images

    private var imageCache: [UUID: NSImage] = [:]

    func image(for item: ClipboardItem) -> NSImage? {
        if let cached = imageCache[item.id] { return cached }
        guard let fileName = item.imageFileName,
              let image = NSImage(contentsOf: storageFolder.appendingPathComponent(fileName)) else { return nil }
        imageCache[item.id] = image
        return image
    }

    private func removeImageFile(_ fileName: String) {
        try? FileManager.default.removeItem(at: storageFolder.appendingPathComponent(fileName))
        imageCache = imageCache.filter { id, _ in items.contains { $0.id == id } }
    }

    // MARK: - Saving

    private func load() {
        guard let data = try? Data(contentsOf: indexFile),
              let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = saved
    }

    private func save() {
        let snapshot = items
        let url = indexFile
        saveQueue.async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: url, options: .atomic)
        }
    }
}
